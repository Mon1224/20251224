async def seed_user(session) -> None:
    exists = await session.scalar(select(User).where(User.phone == DEMO_USER["phone"]))
    if exists:
        print(f"跳过（已存在）：用户 {DEMO_USER['phone']}")
        return
    password_hash = bcrypt.hashpw(DEMO_USER["password"].encode(), bcrypt.gensalt()).decode()
    session.add(
        User(
            phone=DEMO_USER["phone"],
            password_hash=password_hash,
            nickname=DEMO_USER["nickname"],
            real_name=DEMO_USER["real_name"],
            id_card_no=DEMO_USER["id_card_no"],
        )
    )
    print(f"已插入：测试账号 {DEMO_USER['phone']} / {DEMO_USER['password']}")


async def seed_products(session) -> None:
    total_clauses = 0
    for item in PRODUCTS:
        data = dict(item)
        clauses = data.pop("clauses")

        exists = await session.scalar(select(Product).where(Product.code == data["code"]))
        if exists:
            print(f"跳过（已存在）：{data['code']} {data['name']}")
            continue

        product = Product(**data)
        session.add(product)
        await session.flush()  # 拿到自增主键，下面建条款要用

        for clause in clauses:
            session.add(Clause(product_id=product.id, **clause))
        total_clauses += len(clauses)

        print(f"已插入：{data['code']} {data['name']}（{len(clauses)} 条条款）")

    print(f"\n合计新增条款 {total_clauses} 条")


async def main() -> None:
    async with BizSessionLocal() as session:
        await seed_user(session)
        await seed_products(session)
        await session.commit()
    await dispose_engines()
    print("种子数据写入完成。")


if __name__ == "__main__":
    asyncio.run(main())
